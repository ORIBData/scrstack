// Lookups per assessment are bounded so one large monorepo cannot stall
// the queue on deps.dev; the rest are retried by the next assessment.
const (
	defaultMetadataLookups = 2000
	maxVersionLookups      = 300
	lookupConcurrency      = 8
)

// enrich completes the scanner's output before it is recorded: licence
// metadata from deps.dev for components without declared or detected
// licences (LIC-001), safe versions for vulnerability entries (VUL-008),
// and the CycloneDX SBOM generated from the component model (SBM-001).
func (w Worker) enrich(ctx context.Context, a assessments.Assessment, output *scanner.Output, revision string) (stages []assessments.Stage, key, digest string, err error) {
	inventoryOK := false
	for _, s := range output.Stages {
		if s.Name == "inventory" {
			inventoryOK = s.Status == "ok"
		}
	}
	if !inventoryOK || len(output.Components) == 0 {
		return []assessments.Stage{{Name: "sbom", Status: "skipped", Detail: "inventory did not complete"}}, "", "", nil
	}
	budget, cancel := context.WithTimeout(ctx, 90*time.Second)
	defer cancel()
	stages = append(stages, w.licenseMetadata(budget, output))
	stages = append(stages, w.safeVersions(budget, output))
	stages = append(stages, w.dependencyPolicy(budget, output))
	kind := "git"
	if a.Request.Target.Type == "image" {
		kind = "image"
	}
	meta := sbom.Meta{AssessmentID: a.ID, Asset: a.Request.Target.Repository, Kind: kind, Revision: revision, Ref: a.Request.Target.Ref, Version: buildinfo.Version(), Generated: time.Now().UTC()}
	document, err := sbom.CycloneDX(meta, output.Components, false)
	if err != nil {
		return append(stages, assessments.Stage{Name: "sbom", Status: "failed", Detail: "SBOM generation failed"}), "", "", nil
	}
	key, digest, err = w.Artifacts.PutSBOM(ctx, document)
	if err != nil {
		return stages, "", "", err
	}
	return append(stages, assessments.Stage{Name: "sbom", Status: "ok", Detail: fmt.Sprintf("CycloneDX 1.6 generated by SCRS from %d packages", len(sbom.Packages(output.Components)))}), key, digest, nil
}

// licenseMetadata fills licences from deps.dev, cached per package version.
func (w Worker) licenseMetadata(ctx context.Context, output *scanner.Output) assessments.Stage {
	counts := map[string]int{}
	pending := map[assessments.PackageKey][]int{}
	for i := range output.Components {
		c := &output.Components[i]
		if c.License != nil {
			counts[c.License.Source]++
			continue
		}
		system, ok := depsdev.System(c.Ecosystem)
		if !ok || w.DepsDev == nil || c.Version == "" {
			// Nothing else can be learnt: evaluated as no licence found.
			c.License = &assessments.ComponentLicense{Expression: license.NoAssertion, Source: "none"}
			counts["none"]++
			continue
		}
		name := c.Name
		if system == "PYPI" {
			name = strings.ToLower(name)
		}
		k := assessments.PackageKey{System: system, Name: name, Version: c.Version}
		pending[k] = append(pending[k], i)
	}
	keys := make([]assessments.PackageKey, 0, len(pending))
	for k := range pending {
		keys = append(keys, k)
	}
	cached, err := w.Store.CachedPackageLicenses(ctx, keys)
	if err != nil {
		cached = map[assessments.PackageKey]assessments.PackageLicenses{}
	}
	toFetch := []assessments.PackageKey{}
	for _, k := range keys {
		if _, ok := cached[k]; !ok {
			toFetch = append(toFetch, k)
		}
	}
	limit := w.DepsDevMaxLookups
	if limit <= 0 {
		limit = defaultMetadataLookups
	}
	if len(toFetch) > limit {
		toFetch = toFetch[:limit]
	}
	fetched := map[assessments.PackageKey]assessments.PackageLicenses{}
	if len(toFetch) > 0 && w.DepsDev != nil {
		var mu sync.Mutex
		jobs := make(chan assessments.PackageKey)
		var wg sync.WaitGroup
		for range lookupConcurrency {
			wg.Add(1)
			go func() {
				defer wg.Done()
				for k := range jobs {
					list, err := w.DepsDev.Licenses(ctx, k.System, k.Name, k.Version)
					mu.Lock()
					switch {
					case err == nil:
						fetched[k] = assessments.PackageLicenses{Licenses: list, Found: true}
					case errors.Is(err, depsdev.ErrNotFound):
						fetched[k] = assessments.PackageLicenses{}
					}
					mu.Unlock()
				}
			}()
		}
	feed:
		for _, k := range toFetch {
			select {
			case jobs <- k:
			case <-ctx.Done():
				break feed
			}
		}
		close(jobs)
		wg.Wait()
		if len(fetched) > 0 {
			saveCtx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
			if err := w.Store.SavePackageLicenses(saveCtx, fetched); err != nil && w.Logger != nil {
				w.Logger.Warn("package metadata cache write failed", "error", err)
			}
			cancel()
		}
	}
	unresolved := 0
	for k, indexes := range pending {
		v, ok := cached[k]
		if !ok {
			v, ok = fetched[k]
		}
		for _, i := range indexes {
			c := &output.Components[i]
			switch {
			case !ok:
				// Lookup failed or over budget: left unresolved, not unknown.
				unresolved++
			case !v.Found || len(v.Licenses) == 0:
				c.License = &assessments.ComponentLicense{Expression: license.NoAssertion, Source: "none", Evidence: "deps.dev"}
				counts["none"]++
			default:
				n := license.All(v.Licenses...)
				c.License = &assessments.ComponentLicense{Expression: n.Expression, Source: "metadata", Declared: strings.Join(v.Licenses, "; "), Evidence: "deps.dev", Refs: n.Refs}
				if c.License.Declared == c.License.Expression {
					c.License.Declared = ""
				}
				counts["metadata"]++
			}
		}
	}
	detail := fmt.Sprintf("declared %d, detected %d, metadata %d, none %d, unresolved %d", counts["declared"], counts["detected"], counts["metadata"], counts["none"], unresolved)
	if w.DepsDev == nil {
		detail += "; package metadata lookups disabled"
	}
	if output.ProjectLicense != nil {
		detail += "; repository licence " + output.ProjectLicense.Expression
	}
	if unresolved > 0 {
		return assessments.Stage{Name: "license", Status: "partial", Detail: detail}
	}
	return assessments.Stage{Name: "license", Status: "ok", Detail: detail}
}

// safeVersions adds fixed and safe versions to each vulnerability entry's
// guidance (VUL-008, RR-013).
type pkgKey struct{ ecosystem, name string }
type compKey struct{ ecosystem, name, version string }

func (w Worker) safeVersions(ctx context.Context, output *scanner.Output) assessments.Stage {
	full := map[pkgKey]*versions.Package{}
	for i := range output.Packages {
		p := &output.Packages[i]
		full[pkgKey{p.Ecosystem, p.Name}] = p
	}
	matched := map[compKey][]versions.Advisory{}
	for _, f := range output.Findings {
		if f.Type != "vulnerability" {
			continue
		}
		k := compKey{f.Component.Ecosystem, f.Component.Name, f.Component.Version}
		if a, ok := scanner.ParseAdvisory(f.Evidence, f.Component.Ecosystem, f.Component.Name); ok {
			matched[k] = append(matched[k], a)
		}
	}
	if len(matched) == 0 {
		return assessments.Stage{Name: "safe_versions", Status: "skipped", Detail: "no vulnerability entries"}
	}
	published := w.publishedVersions(ctx, matched)
	results := map[compKey]versions.Safe{}
	errorsSeen, registry := 0, 0
	for k, advisories := range matched {
		list := published[pkgKey{k.ecosystem, k.name}]
		if list != nil {
			registry++
		}
		safe := versions.SafeVersions(k.ecosystem, k.name, k.version, advisories, full[pkgKey{k.ecosystem, k.name}], list)
		if safe.Basis.Error != "" {
			errorsSeen++
		}
		results[k] = safe
	}
	for i := range output.Findings {
		f := &output.Findings[i]
		if f.Type != "vulnerability" {
			continue
		}
		safe, ok := results[compKey{f.Component.Ecosystem, f.Component.Name, f.Component.Version}]
		if !ok {
			continue
		}
		guidance := map[string]any{}
		_ = json.Unmarshal(f.Guidance, &guidance)
		guidance["fixed_versions"] = safe.Fixed
		guidance["safe_versions"] = safe.Safe
		guidance["safe_basis"] = safe.Basis
		if safe.SmallestUpgrade != "" {
			guidance["smallest_safe_upgrade"] = safe.SmallestUpgrade
		}
		if safe.Latest != "" {
			guidance["latest_safe"] = safe.Latest
		}
		if raw, err := json.Marshal(guidance); err == nil {
			f.Guidance = raw
		}
	}
	detail := fmt.Sprintf("%d vulnerable packages; %d with registry version lists; %d with full mirror advisory sets", len(matched), registry, len(full))
	if errorsSeen > 0 {
		return assessments.Stage{Name: "safe_versions", Status: "partial", Detail: detail + fmt.Sprintf("; %d could not be ordered", errorsSeen)}
	}
	return assessments.Stage{Name: "safe_versions", Status: "ok", Detail: detail}
}

// publishedVersions reads version lists from the cache or deps.dev; a
// package missing from the result has no list (only fixed versions from
// advisories are then candidates).
func (w Worker) publishedVersions(ctx context.Context, matched map[compKey][]versions.Advisory) map[pkgKey][]string {
	out := map[pkgKey][]string{}
	if w.DepsDev == nil {
		return out
	}
	bySystem := map[string]map[string]pkgKey{}
	for k := range matched {
		system, ok := depsdev.System(k.ecosystem)
		if !ok {
			continue
		}
		name := k.name
		if system == "PYPI" {
			name = strings.ToLower(name)
		}
		if bySystem[system] == nil {
			bySystem[system] = map[string]pkgKey{}
		}
		bySystem[system][name] = pkgKey{k.ecosystem, k.name}
	}
	lookups := 0
	for system, names := range bySystem {
		list := make([]string, 0, len(names))
		for name := range names {
			list = append(list, name)
		}
		cached, err := w.Store.CachedPackageVersions(ctx, system, list)
		if err != nil {
			cached = map[string][]string{}
		}
		fetched := map[string][]string{}
		for _, name := range list {
			if versionsList, ok := cached[name]; ok {
				if len(versionsList) > 0 {
					out[names[name]] = versionsList
				}
				continue
			}
			if lookups >= maxVersionLookups || ctx.Err() != nil {
				continue
			}
			lookups++
			got, err := w.DepsDev.Versions(ctx, system, name)
			switch {
			case err == nil:
				fetched[name] = got
				out[names[name]] = got
			case errors.Is(err, depsdev.ErrNotFound):
				fetched[name] = nil
			}
		}
		if len(fetched) > 0 {
			saveCtx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
			if err := w.Store.SavePackageVersions(saveCtx, system, fetched); err != nil && w.Logger != nil {
				w.Logger.Warn("package version cache write failed", "error", err)
			}
			cancel()
		}
	}
	return out
}
